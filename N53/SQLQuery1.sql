CREATE PROC sp_TimSach
(
    @TenSach NVARCHAR(100)
)
AS
BEGIN
    SELECT *
    FROM SACH
    WHERE TenSach LIKE '%' + @TenSach + '%'
END
GO

EXEC sp_TimSach N'SQL';

CREATE PROC sp_DemSach
(
    @Tong INT OUTPUT
)
AS
BEGIN
    SELECT @Tong = COUNT(*)
    FROM SACH
END
GO

DECLARE @Tong INT

EXEC sp_DemSach
    @Tong OUTPUT

PRINT @Tong

CREATE FUNCTION fn_TinhTien
(
    @Gia FLOAT,
    @SoLuong INT
)
RETURNS FLOAT
AS
BEGIN
    RETURN @Gia * @SoLuong
END
GO

