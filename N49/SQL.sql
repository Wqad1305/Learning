CREATE VIEW vSinhVien
AS
SELECT *
FROM SinhVien
GO

CREATE PROC sp_DanhSachSV
AS
BEGIN
    SELECT *
    FROM SinhVien
END
GO

CREATE PROC sp_SVDuoi5
AS
BEGIN
    SELECT *
    FROM SinhVien
    WHERE Diem < 5
END
GO

CREATE PROC sp_ThemSV
    @MaSV CHAR(5),
    @HoTen NVARCHAR(50),
    @Diem FLOAT,
    @MaLop CHAR(5)
AS
BEGIN
    INSERT INTO SinhVien
    VALUES(@MaSV,@HoTen,@Diem,@MaLop)
END
GO

CREATE FUNCTION fn_DemSV()
RETURNS INT
AS
BEGIN
    DECLARE @SL INT

    SELECT @SL = COUNT(*)
    FROM SinhVien

    RETURN @SL
END
GO

CREATE FUNCTION fn_SVDuoi5()
RETURNS TABLE
AS
RETURN
(
    SELECT *
    FROM SinhVien
    WHERE Diem < 5
)
GO

CREATE TRIGGER trg_TangSiSo
ON SinhVien
AFTER INSERT
AS
BEGIN
    UPDATE Lop
    SET SiSo = SiSo + 1
    WHERE MaLop IN
    (
        SELECT MaLop
        FROM inserted
    )
END
GO

