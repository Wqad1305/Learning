CREATE TABLE Lop
(
    MaLop CHAR(5) PRIMARY KEY,
    TenLop NVARCHAR(50) NOT NULL,
    SiSo INT DEFAULT 0
)

CREATE TABLE SinhVien
(
    MaSV CHAR(5) PRIMARY KEY,
    HoTen NVARCHAR(50) NOT NULL,
    Diem FLOAT,
    MaLop CHAR(5),

    FOREIGN KEY (MaLop)
    REFERENCES Lop(MaLop)
)

