CREATE PROC SP_MAKH
(
	@MAKH CHAR(10),
	@TONGSODONHANG INT OUTPUT,
	@DOANHTHU FLOAT OUTPUT
)
AS
BEGIN
	SELECT @TONGSODONHANG=COUNT(CTDH.MADH) ,@DOANHTHU=SUM(DONGIA*SOLUONG) 
	FROM CHITIETDONHANG CTDH,DONHANG DH
	WHERE MAKH=@MAKH AND CTDH.MADH=DH.MADH
END

DECLARE @TONGSODONHANG INT ,@DOANHTHU FLOAT
EXEC SP_MAKH 'KH001',@TONGSODONHANG OUTPUT,@DOANHTHU OUTPUT

