DECLARE CUR_CAPNHAT CURSOR
FOR
SELECT MAKH
FROM KHACH

OPEN CUR_CAPNHAT

DECLARE @MAKH CHAR(10)
DECLARE @DOANHTHU FLOAT

FETCH NEXT FROM CUR_CAPNHAT INTO @MAKH
WHILE @@FETCH_STATUS=0

BEGIN
	SELECT @DOANHTHU=SUM(SOLUONG*DONGIA)
	FROM CHITIETHOADON CTHD,DONHANG DG,KHACH K
	WHERE @MAKH=MAKH AND CTHD.MAHG=DG.MAHG AND DG.MAKH=K.MAKH

	IF @DOANHTHU<5000000
	UPDATE KHACH
	SET LOAIKH=N'PHOTHONG'
	WHERE MAKH=@MAKH

	ELSE IF @DOANHTHU<20000000
	UPDATE KHACH
	SET LOAIKH=N'THANH VIEN'
	WHERE MAKH=@MAKH

	ELSE 
	UPDATE KHACH
	SET LOAIKH=N'VIP'
	WHERE MAKH=@MAKH

	FETCH NEXT FROM CUR_CAPNHAT INTO @MAKH
END
CLOSE CUR_CAPNHAT
DEALLOCATE CUR_CAPNHAT


