DECLARE   CUR_DONHANG CURSOR
FOR 
SELECT MADH
FROM DONHANG

OPEN CUR_DONHANG 
DECLARE @MADH CHAR(10)
DECLARE @TONGTIEN FLOAT
FETCH NEXT FROM CUR_DONHANG INTO @MADH
WHILE @@FETCH_STATUS=0
BEGIN 
	SELECT @TONGTIEN=SUM(SOLUONG*DONGIA)
	FROM CHITIETHOADON
	WHERE @MADH=MADH

	IF @TONGTIEN>10000000
	UPDATE DONHANG
	SET TRANGTHAI=N'DON LON'
	WHERE @MADH=MADH
	
	ELSE 
	UPDATE DONHANG
	SET TRANGTHAI=N'DON THUONG'
	WHERE @MADH=MADH
	FETCH NEXT FROM CUR_DONHANG INTO @MADH
END
CLOSE CUR_DONHANG
DEALLOCATE CUR_DONHANG  


