CREATE PROC SP_MADH
(
	@MADH CHAR(10),
	@HOTEN NVARCHAR(20) OUTPUT,
	@TRANGTHAI NCHAR(10) OUTPUT
)
AS
BEGIN
	SELECT @HOTEN=K.HOTEN,@TRANGTHAI=DH.TRANGTHAI
	FROM KHACH K,DONHANG DH
	WHERE K.MAKH=DH.MAKH
		AND MADH=@MADH
END


DECLARE @HOTEN NVARCHAR(20), @TRANGTHAI NCHAR(10)
EXEC SP_MADH 'DH001',@HOTEN OUTPUT,@TRANGTHAI OUTPUT

